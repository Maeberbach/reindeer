#!/usr/bin/env node
/**
 * Build the Registry client for the in-thread preview.
 *
 * The preview runs in a sandboxed iframe with no IndexedDB, and the deploy step
 * refuses any bundle that references it. The real app needs IndexedDB — a room
 * recording is tens of megabytes of binary and there is nowhere else to put it —
 * so this produces a copy with the offline queue swapped for the honest stub
 * that reports it cannot hold anything back.
 *
 * The preview is therefore a faithful view of every screen and every flow except
 * offline capture, which cannot be demonstrated in an iframe at all and has to
 * be tried on a real phone at a real URL.
 *
 *   node scripts/build-registry-preview.mjs
 */
import { cp, rm, readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'apps/legacy-registry/client');
const out = join(root, 'apps/legacy-registry/preview');

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await cp(src, out, { recursive: true });

// The stub takes the real file's name so index.html needs no edit.
await cp(join(out, 'offline-queue-unavailable.js'), join(out, 'offline-queue.js'));
await rm(join(out, 'offline-queue-unavailable.js'));

// A leftover reference would be flagged by the deploy scanner and would also be
// a lie about what this build can do, so fail loudly rather than ship it.
const banned = ['indexedDB', 'localStorage', 'sessionStorage', 'requestPointerLock', 'requestFullscreen'];
const offenders = [];
for (const file of ['app.js', 'offline-queue.js', 'index.html', 'sw.js']) {
  let text;
  try {
    text = await readFile(join(out, file), 'utf8');
  } catch {
    continue;
  }
  for (const token of banned) {
    if (text.includes(token)) offenders.push(`${file}: ${token}`);
  }
}
if (offenders.length) {
  console.error('Preview build still references APIs the iframe forbids:');
  for (const o of offenders) console.error(`  - ${o}`);
  process.exit(1);
}

// A visible, honest note so nobody mistakes the preview for the shipping app.
const marker = join(out, 'PREVIEW-ONLY.txt');
await writeFile(
  marker,
  'Generated by scripts/build-registry-preview.mjs. Do not edit.\n' +
    'The offline queue is stubbed out because the preview iframe has no IndexedDB.\n' +
    'The real client is apps/legacy-registry/client.\n',
);

console.log(`Preview build written to apps/legacy-registry/preview (offline queue stubbed).`);
